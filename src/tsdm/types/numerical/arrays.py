    # * (multiplication)
    def __mul__(self, other: Self | T | complex, /) -> Self: ...
    def __rmul__(self, other: Self | T | complex, /) -> Self: ...
    # ** (power)
    def __pow__(self, exponent: Self | T | complex, /) -> Self: ...
    def __rpow__(self, base: Self | T | complex, /) -> Self: ...
    # / (true division)
    def __truediv__(self, other: Self | T | complex, /) -> Self: ...
