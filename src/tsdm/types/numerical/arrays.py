@runtime_checkable
class SpanLikeArray[
    SpanT: SpanLikeScalar = Any,
](
    ArraySupportsComparison[SpanT],
    Protocol,
):
    r"""Protocol for timedelta array-like types supporting standard timedelta operations."""

    def min(self) -> Self | SpanLikeScalar | Any: ...
    def max(self) -> Self | SpanLikeScalar | Any: ...

    # + (positive)
    def __pos__(self) -> Self: ...
    # - (negation)
    def __neg__(self) -> Self: ...
    # absolute value abs()
    def __abs__(self) -> Self: ...

    # + (addition)
    def __add__(self, other: Self | SpanT, /) -> Self: ...
    def __radd__(self, other: Self | SpanT, /) -> Self: ...
    # - (subtraction)
    def __sub__(self, other: Self | SpanT, /) -> Self: ...
    def __rsub__(self, other: Self | SpanT, /) -> Self: ...
    # * (multiplication)
    def __mul__(self, other: int, /) -> Self: ...
    def __rmul__(self, other: int, /) -> Self: ...
    # / (division)
    # @overload  # NOTE: 'Self | Any' to fix numpy overload issue
    # def __truediv__(self, other: int, /) -> Self | Any: ...
    # @overload
    def __truediv__(self, other: Self | SpanT, /) -> FloatArray: ...

    # FIXME: disabled since not supported by all implementations
    # # // (floor division)
    # @overload
    # def __floordiv__(self, other: int, /) -> Self: ...
    # @overload
    # def __floordiv__(self, other: Self | T, /) -> IntegerArray: ...
    # # % (modulo)
    # def __mod__(self, other: Self, /) -> Self: ...
    # # divmod
    # def __divmod__(self, other: Self | T, /) -> tuple[IntegerArray, Self]: ...


@runtime_checkable
class TimedeltaArray[SpanT: SpanLikeScalar = Any](
    SpanLikeArray[SpanT | timedelta],
    Protocol,
):
    r"""Protocol for timedelta array-like types supporting standard timedelta operations."""


@runtime_checkable
class TimeLikeArray[
    TimeT: TimeLikeScalar = Any,
    DualT: SpanLikeScalar = Any,
](
    ArraySupportsComparison[TimeT],
    Protocol,
):
    r"""Protocol for timestamp array-like types supporting standard datetime operations."""

    def min(self) -> Self | TimeLikeScalar | Any: ...
    def max(self) -> Self | TimeLikeScalar | Any: ...

    # + (addition with timedelta)
    def __add__(self, other: DualT, /) -> Self: ...
    def __radd__(self, other: DualT, /) -> Self: ...
    # - (subtraction with datetime)
    def __sub__(self, other: Self | TimeT, /) -> DualT: ...
    def __rsub__(self, other: Self | TimeT, /) -> DualT: ...


@runtime_checkable
class DatetimeArray[
    TimeT: TimeLikeScalar = Any,
    DualT: SpanLikeScalar = Any,
](
    TimeLikeArray[TimeT | datetime, DualT | timedelta],
    Protocol,
):
    r"""Protocol for datetime array-like types supporting standard datetime operations."""
