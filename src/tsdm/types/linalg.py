    @overload
    def mean(self, axis: Axis, /) -> Scalar | Self: ...

    @overload
    def sum(self) -> Self: ...
    @overload
    def sum(self, axis: Axis, /) -> Self: ...

    @overload
    def prod(self) -> Scalar | Self: ...
    @overload
    def prod(self, axis: int, /) -> Scalar | Self: ...

    @overload
    def round(self) -> Self: ...
    @overload
    def round(self, *, decimals: int) -> Self: ...

