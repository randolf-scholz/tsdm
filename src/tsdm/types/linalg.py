@runtime_checkable
class BooleanArray[T](
    # BaseArray,
    # SupportsVectorComparison[T | bool],
    Protocol,
):
    r"""Protocol for boolean array-like types supporting standard boolean operations."""

    # Using Protocol here to allow for different return types
    def __invert__(self) -> Self: ...
    def all(self) -> BoolScalar: ...
    def any(self) -> BoolScalar: ...

    # region binary operations ---------------------------------------------------------
    # FIXME: https://github.com/python/typing/issues/2021
    #   Because of the current spec, we need overloads instead of simply unions.
    def __and__(self, other: Self | T | bool, /) -> Self: ...
    def __rand__(self, other: Self | T | bool, /) -> Self: ...

    def __or__(self, other: Self | T | bool, /) -> Self: ...
    def __ror__(self, other: Self | T | bool, /) -> Self: ...

    def __xor__(self, other: Self | T | bool, /) -> Self: ...
    def __rxor__(self, other: Self | T | bool, /) -> Self: ...

    # endregion binary  operations -----------------------------------------------------

    # region comparison operations -----------------------------------------------------
    def __eq__(self, other: Self | T | Any, /) -> Self: ...  # type: ignore[override]  # pyright: ignore[reportIncompatibleMethodOverride]
    def __ne__(self, other: Self | T | Any, /) -> Self: ...  # type: ignore[override]  # pyright: ignore[reportIncompatibleMethodOverride]
